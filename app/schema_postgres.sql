CREATE TRIGGER invoice_no_delete BEFORE DELETE ON invoices FOR EACH ROW EXECUTE FUNCTION krein_refuse('Issued invoices are immutable');
CREATE TRIGGER invoice_no_update BEFORE UPDATE ON invoices FOR EACH ROW
  WHEN (NEW.id IS DISTINCT FROM OLD.id OR NEW.company_id IS DISTINCT FROM OLD.company_id OR NEW.contract_id IS DISTINCT FROM OLD.contract_id
        OR NEW.number IS DISTINCT FROM OLD.number OR NEW.period IS DISTINCT FROM OLD.period OR NEW.created_at IS DISTINCT FROM OLD.created_at)
  EXECUTE FUNCTION krein_refuse('Issued invoices are immutable: only amounts, due date and lines can be revised, and every revision is kept');
