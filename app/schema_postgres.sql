CREATE VIEW contract_people AS
 SELECT c.id contract_id, c.company_id, c.tenant_id, 1 main FROM contracts c
 UNION ALL SELECT ct.contract_id, ct.company_id, ct.tenant_id, 0 FROM contract_tenants ct WHERE ct.removed_at IS NULL;

-- Protected records: the same rules as the SQLite triggers. Errors use SQLSTATE 23000 (integrity constraint), so the app
-- handles them exactly like the SQLite RAISE(ABORT) errors.
CREATE FUNCTION krein_refuse() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = '23000';
END $$;

-- refuse unless a privacy erasure is running (it may rewrite messages and repair notes)
CREATE FUNCTION krein_refuse_unless_erasure() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM privacy_erasure) THEN
    RAISE EXCEPTION '%', TG_ARGV[0] USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END $$;

CREATE FUNCTION krein_contract_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT ((OLD.status = 'pending signature' AND NEW.status = 'active' AND NEW.company_id = OLD.company_id AND NEW.property_id = OLD.property_id
           AND NEW.tenant_id = OLD.tenant_id AND NEW.start_date = OLD.start_date AND NEW.end_date IS NOT DISTINCT FROM OLD.end_date)
       OR (NEW.signed_on IS NOT DISTINCT FROM OLD.signed_on AND NEW.company_id = OLD.company_id AND NEW.property_id = OLD.property_id
           AND NEW.start_date = OLD.start_date
           AND EXISTS (SELECT 1 FROM contract_handovers h WHERE h.contract_id = OLD.id AND h.from_tenant_id = OLD.tenant_id
                       AND h.to_tenant_id = NEW.tenant_id AND h.applied = 0))) THEN
    RAISE EXCEPTION 'Contract identity is locked' USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER ledger_no_change BEFORE UPDATE OR DELETE ON ledger FOR EACH ROW EXECUTE FUNCTION krein_refuse('Ledger entries are immutable');
