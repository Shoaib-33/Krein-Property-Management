-- The Krein database in PostgreSQL (used when DATABASE_URL is set): the same tables as SQLite after migration V42
-- (app/db.py SCHEMA plus app/migrations.py V2-V42). Later changes go in app/migrations.py, POSTGRES, as well as in SQLite.
-- Types: INTEGER -> BIGINT, REAL -> DOUBLE PRECISION, BLOB -> BYTEA, users.email COLLATE NOCASE -> CITEXT.
CREATE EXTENSION IF NOT EXISTS citext SCHEMA public;

CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email public.citext NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, global_admin BIGINT NOT NULL DEFAULT 0, active BIGINT NOT NULL DEFAULT 1
);
CREATE TABLE companies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, kvk TEXT NOT NULL DEFAULT '', address TEXT NOT NULL DEFAULT '',
 payment_instructions TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, review_invoices BIGINT NOT NULL DEFAULT 0, bank_mode TEXT CHECK(bank_mode IN ('auto','review'))
);
CREATE TABLE sessions (
 token_hash TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), expires_at TEXT NOT NULL, csrf TEXT NOT NULL, last_active TEXT
);
CREATE TABLE login_attempts (
 key TEXT PRIMARY KEY, attempts BIGINT NOT NULL, blocked_until DOUBLE PRECISION NOT NULL
);
CREATE TABLE owners (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), name TEXT NOT NULL,
 email TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '', payout_details TEXT NOT NULL DEFAULT '',
 archived_at TEXT, created_at TEXT NOT NULL, collects_rent BIGINT NOT NULL DEFAULT 0, bank_mode TEXT CHECK(bank_mode IN ('auto','review'))
);
CREATE TABLE portfolios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), owner_id BIGINT NOT NULL REFERENCES owners(id),
 name TEXT NOT NULL, fee_percent DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK(fee_percent>=0 AND fee_percent<=100), created_at TEXT NOT NULL, archived_at TEXT,
 UNIQUE(company_id,name)
);
CREATE TABLE properties (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), name TEXT NOT NULL,
 address TEXT NOT NULL, city TEXT NOT NULL, postcode TEXT NOT NULL DEFAULT '', kind TEXT NOT NULL DEFAULT 'Apartment',
 rooms BIGINT NOT NULL DEFAULT 1, area DOUBLE PRECISION NOT NULL DEFAULT 0, energy_label TEXT NOT NULL DEFAULT 'Unknown',
 bag_id TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL, portfolio_id BIGINT REFERENCES portfolios(id)
);
CREATE TABLE tenants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), name TEXT NOT NULL,
 email TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '', language TEXT NOT NULL DEFAULT 'nl', created_at TEXT NOT NULL, archived_at TEXT, scope_owner_id BIGINT REFERENCES owners(id), erased_at TEXT, co_of BIGINT REFERENCES tenants(id)
);
CREATE TABLE contracts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), property_id BIGINT NOT NULL REFERENCES properties(id),
 tenant_id BIGINT NOT NULL REFERENCES tenants(id), signed_on TEXT NOT NULL, start_date TEXT NOT NULL, end_date TEXT,
 status TEXT NOT NULL DEFAULT 'active', deposit_cents BIGINT NOT NULL DEFAULT 0, created_at TEXT NOT NULL, split_mode TEXT NOT NULL DEFAULT ''
);
CREATE TABLE rent_versions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), contract_id BIGINT NOT NULL REFERENCES contracts(id),
 effective_from TEXT NOT NULL, basic_cents BIGINT NOT NULL CHECK(basic_cents>=0), service_cents BIGINT NOT NULL CHECK(service_cents>=0),
 created_at TEXT NOT NULL, created_by BIGINT REFERENCES users(id), UNIQUE(contract_id,effective_from)
);
CREATE TABLE invoices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id), contract_id BIGINT NOT NULL REFERENCES contracts(id),
